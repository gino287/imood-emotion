"""判斷一支影片裡有哪些情緒、發生在第幾秒。兩種判法並列。

兩支腳本輸出的結構刻意一樣（labels_present / clip_counts / clips），
所以可以直接用 sourcing/mapping/compare.py 並排對照。

────────────────────────────────────────────────────────────────────────
檔案
────────────────────────────────────────────────────────────────────────

  text_timeline.py   看**文字**：yt-dlp 抽音訊 → faster-whisper 轉逐字稿
                     → BERT 逐句判 8 類 → 套 NATIVE_TO_FIVE → 五類時間軸。
                     輸出 _local/sourcing/timelines/{uid}.json，
                     另外 --report 會產出 material_table.json。
                       --uid bili:BV1RD421T7S9
                       --verdict keep --limit 20     跑粗篩活下來的
                       --report                      只彙整已跑完的，不重跑
                       --remap                       換映射／換門檻後重算，不重跑模型
                       --min-clips 3 --min-confidence 0.5 --min-clip 2.0
                       --device cuda --whisper small

                     ⚠️ **實測不可用於判表情**，見下方。現在的用途剩兩個：
                        一、產出逐字稿（eval/scripts/build_spoken_set.py 吃它）
                        二、當作「文字判不出表情」的對照組

  face_timeline.py   ★ 看**臉**：yt-dlp 抽 480p 影格（2 fps）→ YuNet 偵測人臉
                     → hsemotion（AffectNet 8 類）→ 套 AFFECT_TO_FIVE → 五類。
                     **同一種表情連續 3 秒以上**才算一個片段。
                     輸出 _local/sourcing/face/{uid}.json，
                     含逐張影格判定（samples）與連續片段（clips）。
                       --uid bili:BV1aM4y117kD
                       --from-timelines --limit 8    跑文字那邊已經跑過的
                       --report                      只看彙整
                       --refresh                     已跑過的也重跑
                     ★ 要一次跑很多支用 scan_batch.py，不要自己寫迴圈。

  scan_batch.py      對整份清單做大規模粗掃，回答「857 個作者裡有沒有人
                     真的四種情緒都出現過」。兩段式，成本差很多：
                       --probe   0.5 fps、360p，只統計各表情的比例（便宜）
                       --full    對粗掃結果好的跑完整 face_timeline（貴）
                     候選只用**時長**篩，不用標題 —— 題材的情緒與臉上的表情
                     實測是兩回事，用題材選人等於把文字那條路失敗的原因搬進來。
                     但題材分數照樣算出來寫進結果，跑完可以反過來檢驗它有沒有預測力。
                       --plan                  只看候選名單與預估時間
                       --probe --limit 40 --sleep 15
                       --full --top 20
                       --report                彙整
                     做完一支存一支，中斷重跑會跳過已完成的，適合開著跑一整夜。

────────────────────────────────────────────────────────────────────────
為什麼最後只採信臉那一邊
────────────────────────────────────────────────────────────────────────

拿 5 支人工看過的影片核對：臉部辨識 5/5 吻合，文字模型至少 2 支嚴重錯誤。
最清楚的一支是彭春花那支平靜講解榮格心理學的影片 —— 因為內容悲傷
（「他不願意看見和接納現實的險惡」這種**在講別人的處境**的句子），
拿到全場最高的 61% 情緒起伏、哀 51 段、信心 0.98，但臉是中性的。

**文字量的是「話題的情緒」，不是「臉上的表情」。** JoyGen 要的是表情。

另一個踩過的坑：提高信心門檻擋不住偽陽性。一支平穩口播的影片
「到現在其實也快乾滿兩個學期了」被判成哀，信心 0.912。
有效的判準是**連續性** —— 真的在生氣的人不會只氣一句話。
所以兩邊都改成「連續好幾段／好幾張都是同一類」才算數
（text 的 --min-clips、face 的 MIN_RUN_FRAMES）。

臉那邊也靠連續性擋掉一個坑：說話張嘴會被 FER 判成「驚訝」
（影格層級可以到 26–51%），但那是散落的單張，連不成 3 秒。

────────────────────────────────────────────────────────────────────────
踩過的坑（會安靜失敗的那種）
────────────────────────────────────────────────────────────────────────

- **AV1 影片 → OpenCV 讀到 0 張影格，不報錯**，表面上看起來像
  「這支偵測不到人臉」。yt-dlp 的 format 字串一定要指定 avc1。
- **直式影片 + `height<=N` 過濾 → 整支影片沒有任何格式可選。**
  手機拍的影片解析度是 360x480、480x640 這種，**height 是長邊**，
  寫 `height<=360` 會把所有格式都排除，而 B站的格式全是分離的視訊／音訊軌，
  連 `b`（最佳合併版）都沒得退，yt-dlp 直接回
  「Requested format is not available」。實測有 **25% 的影片是這樣整支失敗的**。
  ⚠️ 這個特別惡劣：直式影片正好是手機自拍的 vlog，也就是最可能有情緒起伏的
  那一批 —— 等於系統性地把最相關的素材整批排除掉，而表面上只看到「失敗」。
  改用 `-S res:N` 排序（res 取短邊）而不是硬條件過濾就沒事了，
  見 `face_timeline.format_args()`。
- **`--download-sections` 不加 `--force-keyframes-at-cuts` 就不裁切長度。**
  粗掃要每個窗 45 秒，B站實際給的是 7 秒到 931 秒都有。
  後果不只是取樣多寡不一 —— scan_batch 會把 `start` 加到窗內的秒數上，
  超抓的那段畫面根本不在 start 的位置，**時間戳會指到影片裡不存在的秒數**
  （實測一支 908 秒的影片記出「第 1598 秒」的片段）。
  而且窗與窗重疊，同一個表情被算成好幾個片段，統計虛胖到看起來
  「這個人四種情緒都有」。這個坑讓 189 筆粗掃全部作廢過一次。
  現在 `download_window()` 抓完會用 ffprobe 驗長度、不對就重抓，
  實際秒數存進 `window_seconds_actual`。
- **下載會間歇性只給前面一小段，單獨跑也會發生**，不是只有搶頻寬時。
  `scan_video(expect_seconds=...)` 的覆蓋率檢查是必要的，不是保險。
- **YuNet 的模型檔走 raw.githubusercontent 會抓到 0 位元組**
  （opencv_zoo 用 git-lfs 存），要走 media.githubusercontent。
  size 檢查沒過就當場刪檔並失敗，不留壞檔在快取裡。
- **hsemotion-onnx 的模型下載是壞的**（它組出 blob/...?raw=true，實測 503），
  而且快取在 ~/.hsemotion，容器每跑一次重抓一次。改成先下載到
  _local/sourcing/models/ 再複製過去。
"""
