# 待GINO改寫
"""取材路線 B 的前半段：把兩份裸網址清單變成有 metadata 的候選清單。

輸入是 JoyGen repo Dataset 段落給的 `tmp/bili_urls.txt` 與 `tmp/dy_urls.txt`
（**只有網址、零 metadata**），輸出全部在 `_local/sourcing/`。

成本由低到高，每一層只處理上一層活下來的。前面幾層便宜，先跑；
不連網的那幾支改規則重跑是零成本的。

────────────────────────────────────────────────────────────────────────
執行順序
────────────────────────────────────────────────────────────────────────

  1. normalize_urls.py   兩份 txt → sources.jsonl（1188 支）        不連網
  2. fetch_bilibili.py   B站官方 API 抓 metadata（約 35 分鐘）        連網
     fetch_douyin.py     抖音走 f2，需要 DOUYIN_COOKIE               連網
  3. group_authors.py    以作者分組，產候選人物排行                不連網
  4. coarse_filter.py    時長／分區／片型關鍵字粗篩                不連網
     covers.py           封面縮圖 + 縮圖牆（肉眼快篩）               連網
  (4b) fetch_channel.py  鎖定某個人之後，抓他頻道的全部作品          連網

────────────────────────────────────────────────────────────────────────
檔案
────────────────────────────────────────────────────────────────────────

  normalize_urls.py  處理原始清單的三個坑：bili_urls.txt 裡混了 10 行抖音
                     （ID 藏在 modal_id= 參數裡，grep BV 會漏掉 9 支）、
                     兩份都有重複行、網址帶追蹤參數。
                     總數 1188 寫成斷言，對不上就是解析漏了東西。
                       --dry-run    只印統計不寫檔

  fetch_bilibili.py  打 /x/web-interface/view，公開影片免登入，一支一請求。
                     順便打 /x/tag/archive/tags 拿 UP 主自訂標籤 ——
                     訪客模式下分區名（tname）回空字串，標籤才是有用的訊號。
                     raw 存在就跳過，所以中斷了直接重跑同一行。
                       --limit 3    小樣本先驗欄位（放大前一定先跑這個）
                       --rebuild    不連網，只從 raw 重抽欄位
                       --no-tags    不抓標籤（省一半請求數）

  fetch_douyin.py    走 f2 的 DouyinHandler。抖音公開影片也多半要 cookie，
                     放在 .env 的 DOUYIN_COOKIE。沒 cookie 也能跑，
                     腳本會把成功率印出來（實測訪客模式 0%）。
                     ⚠️ 抖音的 duration 單位是毫秒、B站是秒，這裡統一換算成秒。
                       --limit / --rebuild / --refetch

  group_authors.py   GROUP BY author_id。**這支的結論比它原本的用途重要**：
                     857 支 B站影片跑出來是 857 個不同作者、零重複 ——
                     JoyGen 是刻意一人只收一支的（lip-sync 訓練集要的是
                     說話人多樣性）。所以「在清單內找同一個人的多支影片」
                     這條路結構上就不存在。
                       --min-videos 3 / --top 20

  coarse_filter.py   完全不連網，只吃 metadata。判定分三檔：
                     drop（明確不對）／keep（命中片型詞）／maybe（都沒命中，
                     留著但排後面）。留 maybe 是因為關鍵字一定有漏，
                     二分的話漏掉的會被靜默丟棄。
                     ⚠️ 實測在這批素材上只刷掉 6.3% —— 這份清單本來就是
                        JoyGen 挑過的單人說話影片，片型早就對了。
                       --show drop  看被刷掉的長什麼樣
                       --exclude-tid 4  排除指定分區

  covers.py          下載封面並拼成縮圖牆。**整條漏斗裡 CP 值最高的一步** ——
                     封面是 metadata 階段唯一能看到「畫面」的東西，
                     一千多張只有幾十 MB，一頁排 100 張，肉眼掃 30 秒
                     就能刷掉一半沒有人臉／是動畫／是遊戲畫面的影片。
                       --download --sheet --verdict keep
                       --from-shortlist   照 deliver/shortlist.py 的排序取

  fetch_channel.py   B站 space API（要 WBI 簽名 + buvid3，比 view 端點麻煩）。
                     用途是把清單當「人的名冊」：臉已經確認可用的人，
                     回他自己的頻道找缺的那幾種情緒。
                     ⚠️ 實測這條也不通，見下方。
                       --mid 20960244 --merge --min-duration 180

────────────────────────────────────────────────────────────────────────
⚠️ 這條路線湊不齊「同一人四種情緒」—— 三個都是量出來的
────────────────────────────────────────────────────────────────────────

1. **清單是一人一支。** 857 支成功 = 857 個不同作者、零重複。

2. **單支影片只有一種情緒基調。** 講述型影片有固定的敘事位置：
   已釋懷的人從頭笑到尾，還在憂愁的人從頭哀到尾。

3. **跨同一人的多支影片也不行 —— 情緒基調是「鏡頭前人設」的屬性。**
   拿臉部驗證確認可用的四月吨吨_ 做過完整測試（fetch_channel.py 抓她頻道
   三支負面題材，含「在德国留学这3年是我人生5年中最漫长的7年」），
   四支約 100 分鐘：**樂 63／37／60／38，哀怒驚全部為 0**。

所以這條路線現在的定位是：真實感素材的來源，以及「為什麼要走演員資料集」
的證據。要做得到「同一人五種情緒」看 sourcing/actors/。
"""
